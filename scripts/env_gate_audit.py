def self_test(inject_fail=False):
    """The synthetic cases; with inject_fail, one expectation is wrong, so
    the caller can check the failure reaches the exit status. Only the
    plain self-test spawns processes, and never this flag's own path."""
    rows, funcs = audit({"src/synth.c": SELF_TEST_SRC, "src/synth.h": SELF_TEST_HDR,
                         "src/other.c": SELF_TEST_OTHER})
    got = {}
    for r in rows:
        for k in r["knobs"]:
            got[k] = (r["verdict"], r["warm"])
    bad = []
    want_all = dict(SELF_TEST_WANT)
    if inject_fail:
        want_all["SYN_HELPER"] = ("TRAP", True)
    for k, want in want_all.items():
        if got.get(k) != want:
            bad.append(f"{k}: want {want}, got {got.get(k)}")
    for k in set(got) - set(SELF_TEST_WANT):
        bad.append(f"{k}: not a gate, read as {got[k]}")
    if not any(r["file"] == "src/synth.h" and r["name"] == "h_gate" for r in rows):
        bad.append("the header's static inline gate is not keyed to its own file")
    fake = sorted({n for _f, n in funcs} & (KEYWORDS | TYPE_WORDS | DECL_WORDS))
    if fake:
        bad.append(f"keywords or type words read as function names: {fake}")
    # the report: its COLD list and its exit status
    buf = io.StringIO()
    rc = report(rows, out=buf)
    listed = set(re.findall(r"^  \S+:\d+  (\w+)  ", buf.getvalue().split("=== COLD")[-1], re.M))
    want_cold = {r["name"] for r in rows if not r["warm"] and r["verdict"] != "TRAP"}
    if "=== COLD" not in buf.getvalue() or listed != want_cold:
        bad.append(f"COLD list {sorted(listed)} != {sorted(want_cold)}")
    if rc != 1:
        bad.append(f"exit status {rc} on a tree with a TRAP and COLD gates")
    crows, _ = audit({"src/clean.c": SELF_TEST_CLEAN})
    crc = report(crows, out=io.StringIO())
    if crc != 0 or len(crows) != 1:
        bad.append(f"clean tree: exit status {crc}, {len(crows)} gate(s)")
    for label, src in (("cold", SELF_TEST_COLD), ("trap", SELF_TEST_TRAP),
                       ("undetermined", SELF_TEST_UND)):
        orows, _ = audit({f"src/{label}.c": src})
        if report(orows, out=io.StringIO()) != 1:
            bad.append(f"a tree whose only fault is {label} exits 0")
    mwhy = [r["why"] for r in rows if "SYN_MACRO" in r["knobs"]]
    if not mwhy or "v == UNSET" not in mwhy[0] or any("None" in r["why"] for r in rows):
        bad.append(f"a guard should print as its source text: {mwhy}")
    lrows, _ = audit({"cli/cli.c": SELF_TEST_CLI, "src/lib.c": SELF_TEST_LIB})
    lw = {k: r["warm"] for r in lrows for k in r["knobs"]}
    if lw != {"SYN_CMAIN": True, "SYN_CWORK": False, "SYN_LIB": False, "SYN_CWORK2": False,
              "SYN_CLIB": False}:
        bad.append(f"cli: want main's gate warm, the worker's and the library's cold, got {lw}")
    wrows, _ = audit({"src/waived.c": SELF_TEST_WAIVED})
    if report(wrows, out=io.StringIO()) != 0 or not (wrows and wrows[0]["waived"]):
        bad.append("a waived TRAP still fails the tree, or isn't marked waived")
    mrows, _ = audit({"src/main.c": SELF_TEST_SRCMAIN})
    if [r["warm"] for r in mrows] != [False]:
        bad.append("a main in src/ is taken as a warm root")
    vrows, _ = audit({"src/waivers.c": SELF_TEST_WAIVERS})
    wv = {k: r["waived"] for r in vrows for k in r["knobs"]}
    want_w = {"SYN_WBODY": "the body form", "SYN_WGNU": "the\n   split signature form",
              "SYN_WEMPTY": EMPTY_WAIVER, "SYN_WSTR": None}
    if {k: (v.split()[0] if v and v != EMPTY_WAIVER else v) for k, v in wv.items()} != \
            {k: (v.split()[0] if v and v != EMPTY_WAIVER else v) for k, v in want_w.items()}:
        bad.append(f"waivers read as {wv}")
    erows = [r for r in vrows if "SYN_WEMPTY" in r["knobs"]]
    if report(erows, out=io.StringIO()) != 1:
        bad.append("a TRAP under an empty waiver passes the run")
    if not inject_fail:
        # the exit status through a process: main() on a tree on disk, and
        # a failing self-test (its own path spawns nothing)
        import subprocess, tempfile
        with tempfile.TemporaryDirectory() as d:
            (pathlib.Path(d) / "src").mkdir()
            (pathlib.Path(d) / "src" / "trap.c").write_text(SELF_TEST_TRAP)
            r = subprocess.run([sys.executable, __file__, "--root", d], capture_output=True)
            if r.returncode != 1:
                bad.append(f"main() on a TRAP tree exits {r.returncode}")
            (pathlib.Path(d) / "src" / "trap.c").write_text(SELF_TEST_CLEAN)
            (pathlib.Path(d) / "src" / ".#lock.c").symlink_to("nowhere@123:456")
            (pathlib.Path(d) / "src" / "latin1.c").write_bytes(b"/* caf\xe9 */\n")
            r = subprocess.run([sys.executable, __file__, "--root", d], capture_output=True)
            if r.returncode != 0:
                bad.append(f"main() on a clean tree exits {r.returncode}")
            (pathlib.Path(d) / "cli").mkdir()
            (pathlib.Path(d) / "cli" / "trap.c").write_text(SELF_TEST_TRAP)
            r = subprocess.run([sys.executable, __file__, "--root", d], capture_output=True)
            if r.returncode != 1:
                bad.append(f"main() doesn't scan cli/: a TRAP there exits {r.returncode}")
        r = subprocess.run([sys.executable, __file__, "--self-test-failing"], capture_output=True)
        if r.returncode == 0:
            bad.append("a failing self-test exits 0")
    n = len(want_all) + 13 + (0 if inject_fail else 4)
    for b in bad:
        print("env_gate_audit --self-test: FAIL " + b)
    print(f"env_gate_audit --self-test: {n - len(bad)}/{n} checks {'PASS' if not bad else 'FAIL'}")
    return 1 if bad else 0


def report(rows, show_all=False, out=sys.stdout):
    """Print the verdicts; the exit status, nonzero on any TRAP, COLD or
    undetermined gate."""
    live = [r for r in rows if not r.get("waived") or r["waived"] == EMPTY_WAIVER]
    waived = [r for r in rows if r.get("waived") and r["waived"] != EMPTY_WAIVER]
    badw = [r for r in rows if r.get("waived") == EMPTY_WAIVER]
    traps = [r for r in live if r["verdict"] == "TRAP"]
    cold = [r for r in live if not r["warm"] and r["verdict"] != "TRAP"]
    und = [r for r in live if r["verdict"] == "latches?"]
    print(f"{len(rows)} lazy env-static gates; {len(traps)} TRAP, {len(cold)} COLD, "
          f"{sum(r['warm'] for r in rows)} warmed, {len(und)} undetermined, "
          f"{len(waived)} waived", file=out)
    for label, group in (("TRAP -- perpetual writer, no warm can quiet it", traps),
                         ("COLD -- latches, but first touch races", cold),
                         ("UNDETERMINED -- the unset value can't be read", und),
                         ("WAIVED -- env-audit-ok, not counted", waived),
                         ("WAIVER ERROR -- env-audit-ok with no reason, not honoured", badw),
                         ("all gates", rows if show_all else [])):
        if not group:
            continue
        print(f"\n=== {label} ===", file=out)
        for r in sorted(group, key=lambda r: (r["file"], r["line"])):
            mark = "" if r["warm"] else "  [cold]"
            print(f"  {r['file']}:{r['line']}  {r['name']}  {','.join(r['knobs'])}{mark}", file=out)
            if r.get("waived") == EMPTY_WAIVER:
                print("      a waiver needs a reason after 'env-audit-ok:'", file=out)
            elif r.get("waived"):
                print(f"      {r['verdict']}, waived: {r['waived']}", file=out)
            elif r["verdict"] in ("TRAP", "latches?"):
                print(f"      {r['why']}", file=out)
    return 1 if traps or cold or und or badw else 0


def main():
    if "--self-test" in sys.argv:
        return self_test()
    if "--self-test-failing" in sys.argv:          # a self-test with one wrong case
        return self_test(inject_fail=True)
    root = pathlib.Path(sys.argv[sys.argv.index("--root") + 1]) if "--root" in sys.argv else ROOT
    # is_file drops a dangling symlink (an editor's .#lock file); a stray
    # byte never stops the run
    files = sorted(str(p) for d in ("src", "cli") for p in (root / d).rglob("*.[ch]") if p.is_file())
    sources = {str(pathlib.Path(f).relative_to(root)):
               pathlib.Path(f).read_text(encoding="utf-8", errors="replace") for f in files}
    rows, _allfuncs = audit(sources)
    if "--json" in sys.argv:
        json.dump(rows, open(sys.argv[sys.argv.index("--json") + 1], "w"), indent=1)
    return report(rows, "--all" in sys.argv)


if __name__ == "__main__":
    sys.exit(main())
