"""Audit every lazy env-static gate in src/ and cli/ for the two ways they go wrong.

The encoder resolves many of its Y264_* knobs (docs/knobs.md counts them)
through lazy statics:

    static int v = -1;
    if (v < 0) { const char *e = y264_env("Y264_FOO"); v = e ? atoi(e) : 1; }

Under GOP-parallel opens these first-touch on whichever worker gets there
first. The races are benign same-value init, but a nonzero TSan floor hides
the next real report -- the 4:4:4 MC border overflow (08-29) sat behind four
of them. Two distinct failures:

  TRAP  the resolved value still satisfies the guard, so the gate re-runs
        the env read and REWRITES its static on EVERY call. A perpetual writer;
        no warm can quiet it. (Y264_WF_CAPK resolved "unset" to -2 under a
        `v < 0` guard and did exactly this.)
  COLD  latches correctly, but nothing resolves it on the main thread before
        the pool exists, so first touch races.

Warmed means reachable from warm_lr_statics, ntp_pool_create or
ntp_bg_create, or in cli/ from main: the CLI resolves its gates on the main
thread before it starts its GOP workers, and a thread's entry function is
only ever passed as an argument, which the walk never follows, so code that
runs only on a worker stays cold. (Whether main's touch comes before the
workers start is not checked.) A warm can only reach a gate through a CALLABLE function: a
static resolved inline inside a hot function is unreachable by construction
and has to be hoisted into an accessor first.

    python3 scripts/env_gate_audit.py            # cold + trap gates
    python3 scripts/env_gate_audit.py --all      # every gate, with verdicts
    python3 scripts/env_gate_audit.py --json out.json
    python3 scripts/env_gate_audit.py --self-test   # every gate shape, synthetic

A gate a reviewer has judged sound can carry an 'env-audit-ok: <reason>'
marker, in comment text only: in a comment that ends on the line directly
above the definition (a block comment may open further up), on the
definition's own lines (a GNU-style 'static int' line above the name is
one of them), or anywhere in the body. It is then listed as waived and
doesn't count. A marker with no reason is an error and fails the run.

Exits nonzero if any TRAP, COLD or undetermined gate is found. Run it after
adding a knob; make test and both CI jobs run --self-test and then the audit.

Known limits, each read wrongly or not at all:
- a K&R-style definition, a function generated by a macro, and a signature
  longer than 12 lines are not read as functions;
- a function-like macro that wraps the reader (KENV("X")) is not seen; a
  knob name given as a same-file #define of a string literal is;
- a latch on a struct member (cfg.v < 0), on a non-static or extern
  variable, or filled through a helper that reads a literal knob itself
  is not read as a gate;
- a Yoda guard (-1 == v), a ~0u sentinel and a while-guard are not read
  as guards, nor is a read in an if's else branch, nor a guard on a local
  copied from a plain static (int v = cached; if (v < 0) ...);
- a latch flag set by atomic_exchange or ++ reads as never assigned;
- whether main's touch of a CLI gate comes before the workers start;
- a thread entry never named as a pthread_create or ntp_* argument (only
  ever passed through a variable or field) reads as warm when a warm
  function names it.

--self-test checks every behaviour above it reads, but it can't catch a
change that drops its own exit status (or main's sys.exit); review that.
"""
import io, re, sys, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WARM_ROOTS = ["warm_lr_statics", "ntp_pool_create", "ntp_bg_create"]


ARRDEF = re.compile(r"\bint\s+(\w+)\[\d+\]\s*=\s*\{([^}]*)\}")
CALL   = re.compile(r"\b(\w+)\s*\(")
IDENT  = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
# words that open a statement, never a function definition
KEYWORDS = {"if", "else", "while", "for", "do", "switch", "case", "return",
            "sizeof", "typedef", "struct", "union", "enum", "goto", "default"}
# type words a '(' can follow in a declarator ('int (*f(void))(int)')
TYPE_WORDS = {"void", "char", "short", "int", "long", "float", "double", "signed",
              "unsigned", "const", "volatile", "static", "inline", "extern"}
# words that take parentheses in a declaration without naming it
DECL_WORDS = {"__attribute__", "__declspec", "_Alignas", "alignas", "__typeof__",
              "typeof", "_Atomic"}


def strip_comments(text):
    """The text with every comment blanked to spaces, newlines kept, so line
    numbers and columns survive. String and character literals are kept."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(re.sub(r"[^\n]", " ", text[i:j]))
            i = j
        elif c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def blank_strings(text):
    """The text with the inside of every string and character literal blanked,
    so a '{' or '(' in a literal never moves a count."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(c + " " * (min(j, n) - i - 1) + (text[j] if j < n else ""))
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def drop_if0(text):
    """The text with every '#if 0' ... '#else'/'#endif' region blanked
    (newlines kept); nested conditionals inside one are not tracked."""
    return re.sub(r"^[ \t]*#[ \t]*if[ \t]+0\b.*?(?=^[ \t]*#[ \t]*(?:else|elif|endif)\b)",
                  lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.M | re.S)


def blank_attributes(text):
    """The text with every __attribute__((...)) group, and every group of
    another declaration word (__typeof__(int), _Alignas(16)), blanked to
    spaces."""
    out, i = [], 0
    rx = r"\b(?:" + "|".join(sorted(DECL_WORDS)) + r")\s*\("
    for m in re.finditer(rx, text):
        if m.start() < i:
            continue
        end = balanced(text, m.end() - 1)
        out.append(text[i:m.start()])
        out.append(re.sub(r"[^\n]", " ", text[m.start():end]))
        i = end
    out.append(text[i:])
    return "".join(out)


def functions(text):
    """(name, line, body, signature) for every function definition.

    A definition starts at column 0, or indented at file scope (inside an
    #ifdef, say). The signature may wrap: lines are joined until its
    parentheses balance. The body's opening brace may sit on the signature's
    last line or on its own line, and a whole definition may sit on one line.
    Comments and __attribute__((...)) groups are blanked first, and every
    count runs on a copy with string literals blanked. A line that opens with
    a statement keyword is never a signature.
    """
    code = blank_attributes(strip_comments(text))
    lines = code.split("\n")
    struct = blank_strings(code).split("\n")
    top = []                                 # brace depth at each line's start
    d = 0
    for ln in struct:
        top.append(d)
        d = max(0, d + ln.count("{") - ln.count("}"))
    i = 0
    while i < len(lines):
        ln = struct[i]
        m = re.match(r"[ \t]*([A-Za-z_]\w*)", ln)
        indented = bool(ln[:1].isspace())
        opens = "(" in ln or (i + 1 < len(struct) and struct[i + 1].lstrip().startswith("("))
        if not m or m.group(1) in KEYWORDS or not opens or \
                (indented and top[i] != 0):
            i += 1
            continue
        # join the signature until its parentheses balance
        sig, j, depth, seen, after = "", i, 0, False, None
        while j < len(lines) and j < i + 12:
            for c, ch in enumerate(struct[j]):
                if ch == "(":
                    depth += 1; seen = True
                elif ch == ")":
                    depth -= 1
                    if seen and depth == 0:
                        sig += struct[j][:c + 1]
                        after = struct[j][c + 1:]
                        break
            if after is not None:
                break
            sig += struct[j] + "\n"
            j += 1
        if after is None:
            i += 1
            continue
        if ";" in after.split("{")[0]:
            i = j + 1                         # a prototype or a declaration
            continue
        k = j
        if "{" not in after:
            k = j + 1
            while k < len(lines) and not struct[k].strip():
                k += 1
            if k >= len(lines) or not struct[k].lstrip().startswith("{"):
                i += 1
                continue
        # brace-count the body from the definition's first line
        depth, e, started = 0, i, False
        while e < len(lines):
            seg = struct[e]
            depth += seg.count("{") - seg.count("}")
            if seg.count("{"):
                started = True
            if started and depth <= 0 and e >= k:
                break
            e += 1
        names = [x for x in IDENT.findall(sig) if x not in DECL_WORDS and x not in TYPE_WORDS]
        if names:
            yield names[0], i + 1, "\n".join(lines[i:e + 1]), sig
        i = e + 1


def as_int(s):
    try:
        return int(s.strip().rstrip(";").strip(), 0)
    except ValueError:
        return None


def satisfies(val, op, sent):
    return {"<": val < sent, "<=": val <= sent, ">": val > sent, ">=": val >= sent,
            "==": val == sent, "!=": val != sent}.get(op)


def params_of(sig):
    """The parameter names of a joined signature, in order."""
    inner = sig[sig.index("(") + 1:sig.rindex(")")]
    out = []
    for part in inner.split(","):
        ids = re.findall(r"[A-Za-z_]\w*", part.split("[")[0])
        if ids and ids[-1] != "void":
            out.append(ids[-1])
    return out


def find_readers(defs):
    """Every function that reads the environment by name: y264_env and getenv,
    and any function that hands one of its own parameters to a reader at any
    argument position (env_int, rc_tunable). Maps the name to (index of the
    knob-name argument, index of the argument a caller's unset value sits in,
    or None)."""
    readers = {"y264_env": (0, None), "getenv": (0, None)}
    changed = True
    while changed:
        changed = False
        for name, _line, body, sig, _rel in defs:
            if name in readers:
                continue
            ps = params_of(sig)
            for r, (ni, _di) in list(readers.items()):
                for m in re.finditer(r"\b" + re.escape(r) + r"\s*\(", body):
                    args = split_args(body[m.end():])
                    if len(args) > ni and args[ni] in ps:
                        k = ps.index(args[ni])
                        rest = [x for x in range(len(ps)) if x != k]
                        readers[name] = (k, rest[0] if rest else None)
                        changed = True
                        break
                if name in readers:
                    break
    return readers


def env_reads(body, readers, macros):
    """(position, knob) for every read of a knob by name in a body: a string
    literal at the reader's name position, or a same-file #define of one."""
    out = []
    rx = re.compile(r"\b(" + "|".join(map(re.escape, readers)) + r")\s*\(")
    for m in rx.finditer(body):
        ni = readers[m.group(1)][0]
        args = split_args(body[m.end():])
        if len(args) <= ni:
            continue
        a = args[ni].strip()
        if a in macros:
            a = macros[a].strip()
        lit = re.fullmatch(r'"([^"]+)"', a)
        if lit:
            out.append((m.start(), lit.group(1)))
    return out


def split_args(text):
    """Top-level comma split of a call's argument text (up to its ')')."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            if depth == 0:
                break
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
            continue
        cur += ch
    out.append(cur.strip())
    return out


def balanced(text, start):
    """Index just past the bracket that closes the one at text[start]."""
    pairs = {"(": ")", "{": "}", "[": "]"}
    want, depth = pairs[text[start]], 0
    for i in range(start, len(text)):
        if text[i] == text[start]:
            depth += 1
        elif text[i] == want:
            depth -= 1
            if depth == 0:
                return i + 1
    return len(text)


def num(tok, macros):
    """An integer constant, a same-file #define of one, or None."""
    tok = tok.strip()
    for _ in range(4):
        m = re.fullmatch(r"\(\s*(.+?)\s*\)", tok)
        if m:
            tok = m.group(1)
            continue
        if tok in macros:
            tok = macros[tok].strip()
            continue
        m = re.fullmatch(r"-\s*\(\s*(.+?)\s*\)", tok)
        if m:
            tok = "-" + m.group(1)
            continue
        break
    if tok in ("true", "false"):
        return int(tok == "true")
    neg = tok.startswith("-")
    body = tok[1:].strip() if neg else tok
    if re.fullmatch(r"0[xX][0-9a-fA-F]+[uUlL]*", body):
        v = int(re.sub(r"[uUlL]+$", "", body), 16)         # 0x7fffffff, 0xffu
        return -v if neg else v
    if re.fullmatch(r"0[0-7]+[uUlL]*", body):
        v = int(re.sub(r"[uUlL]+$", "", body), 8)          # 0777
        return -v if neg else v
    tok = re.sub(r"(?<=[0-9.])[uUlLfF]+$", "", tok)    # 1.0f, 10UL
    v = as_int(tok)
    if v is None:
        try:
            v = float(tok)
        except ValueError:
            return None
    return v


CMP = re.compile(r"(?<![\w.>])([A-Za-z_]\w*)(?:\[[^\]]*\])?\s*(<=|>=|==|!=|<|>)\s*(\(?-?[\w.]+\)?)")
NOT = re.compile(r"!\s*([A-Za-z_]\w*)\b(?!\s*[(\[.])")
NEG = {"<": ">=", "<=": ">", ">": "<=", ">=": "<", "==": "!=", "!=": "=="}


UNASSIGNED = "unassigned"


def env_locals(body, readers):
    """Locals a body loads from an env read: NULL when the knob is unset."""
    rx = r"\b(\w+)\s*=\s*(?:" + "|".join(re.escape(r) for r, (_n, d) in readers.items()
                                          if d is None) + r")\s*\("
    return set(re.findall(rx, body))


def cond_unset(cond, envl, readers):
    """A condition's truth with the knob unset, or None when it can't be
    read: `!s`, `!s || ...` and `s == NULL` are true, `s`, `s && ...` and
    `s != NULL` false, s an env local or a reader call."""
    c = cond.strip()
    while c.startswith("(") and balanced(c, 0) == len(c):
        c = c[1:-1].strip()
    rd = r"(?:" + "|".join(re.escape(r) for r, (_n, d) in readers.items() if d is None) + r")\s*\([^()]*\)"
    x = r"(?:" + ("|".join(map(re.escape, envl)) + "|" if envl else "") + rd + r")"
    if re.match(r"!\s*" + x + r"\s*(\|\||$)", c) or re.fullmatch(x + r"\s*==\s*NULL", c):
        return True
    if re.match(x + r"\s*(&&|$)", c) or re.fullmatch(x + r"\s*!=\s*NULL", c):
        return False
    return None


def eval_unset(expr, region, envl, readers, macros, depth=0):
    """An expression's value with the knob unset, or None."""
    e = expr.strip()
    if depth > 6 or not e:
        return None
    while True:
        m = re.fullmatch(r"\(\s*(\w+\s*\**)\s*\)\s*(.+)", e, re.S)   # a cast
        if m and balanced(e, 0) != len(e):
            e = m.group(2).strip(); continue
        if e.startswith("(") and balanced(e, 0) == len(e):
            e = e[1:-1].strip(); continue
        break
    depth_p, q, open_q = 0, -1, 0
    for i, ch in enumerate(e):                       # top-level ternary
        if ch in "([":
            depth_p += 1
        elif ch in ")]":
            depth_p -= 1
        elif ch == "?" and depth_p == 0:
            if q < 0:
                q = i
            open_q += 1
        elif ch == ":" and depth_p == 0 and q >= 0 and (open_q := open_q - 1) == 0:
            t = cond_unset(e[:q], envl, readers)
            if t is None:
                t = cond_value(e[:q], region, envl, readers, macros, depth)
            if t is None:
                return None                          # a condition it can't read
            # the ':' that closes the first '?' splits this one, so a ternary
            # nested in either branch stays whole
            br = e[q + 1:i] if t else e[i + 1:]
            return eval_unset(br, region, envl, readers, macros, depth + 1)
    rd = r"(?:" + "|".join(re.escape(r) for r, (_n, d) in readers.items() if d is None) + r")\s*\([^()]*\)"
    if re.fullmatch(rd + r"\s*!=\s*NULL", e) or re.fullmatch(rd, e):
        return 0
    if cond_unset(e, envl, readers) is not None and re.search(r"&&|\|\||==|!=|^!", e):
        return int(cond_unset(e, envl, readers))     # 's && atoi(s)' is 0
    for r, (_ni, idx) in readers.items():
        mm = re.match(re.escape(r) + r"\s*\(", e)
        if mm and idx is not None:
            args = split_args(e[mm.end():])
            return num(args[idx], macros) if len(args) > idx else None
    if re.fullmatch(r"[A-Za-z_]\w*", e) and e not in macros and e not in envl:
        mm = re.search(r"\b" + re.escape(e) + r"\s*=(?!=)\s*([^;]+);", region)
        if mm:                                       # a local carrying it
            return eval_unset(mm.group(1), region, envl, readers, macros, depth + 1)
    return num(e, macros)


def cond_value(cond, region, envl, readers, macros, depth):
    """A condition over locals whose unset values are known ('x > 0',
    '(x & 1)'), evaluated as integer arithmetic, or None."""
    names = set(re.findall(r"[A-Za-z_]\w*", cond))
    vals = {}
    for n in names:
        v = eval_unset(n, region, envl, readers, macros, depth + 1)
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            return None
        vals[n] = v
    expr = re.sub(r"[A-Za-z_]\w*", lambda m: repr(vals[m.group(0)]), cond)
    expr = expr.replace("&&", " and ").replace("||", " or ")
    expr = re.sub(r"!(?!=)", " not ", expr)
    if not re.fullmatch(r"[\d\s().+\-*/%<>=!&|^~a-z]*", expr):
        return None
    try:
        return bool(eval(expr, {"__builtins__": {}}, {}))
    except Exception:
        return None


def stmt_end(text, at):
    """Index just past the statement that starts at `at` (whitespace
    skipped): a braced block, an if with its else chain, or up to ';'."""
    k = at + len(text[at:]) - len(text[at:].lstrip())
    if text.startswith("{", k):
        return balanced(text, k)
    m = re.match(r"if\s*\(", text[k:])
    if m:
        c1 = balanced(text, k + m.end() - 1)
        e = stmt_end(text, c1)
        m2 = re.match(r"\s*else\b", text[e:])
        return stmt_end(text, e + m2.end()) if m2 else e
    semi = text.find(";", k)
    return len(text) if semi < 0 else semi + 1


def if_spans(region, upto):
    """(condition, then span, else span or None) for every if that starts
    before `upto` in `region`."""
    for m in re.finditer(r"\bif\s*\(", region[:upto]):
        c0 = m.end() - 1
        c1 = balanced(region, c0)
        s1 = stmt_end(region, c1)
        m2 = re.match(r"\s*else\b", region[s1:])
        els = (s1 + m2.end(), stmt_end(region, s1 + m2.end())) if m2 else None
        yield region[c0 + 1:c1 - 1], (c1, s1), els


def skipped_unset(region, at, envl, readers):
    """Whether the statement at `at` sits in a branch the unset knob never
    takes: under an if it makes false (`if (s) v = atoi(s);`), or in the
    else of one it makes true (`if (!s) v = 0; else v = atoi(s);`)."""
    for cond, (a, b), els in if_spans(region, at):
        t = None
        if a <= at < b or (els and els[0] <= at < els[1]):
            t = cond_unset(cond, envl, readers)
        if a <= at < b and t is False:
            return True
        if els and els[0] <= at < els[1] and t is True:
            return True
    return False


def under_if(region, at):
    """Whether the statement at `at` sits under an if, or its else, inside
    `region`."""
    for _cond, (a, b), els in if_spans(region, at):
        if a <= at < b or (els and els[0] <= at < els[1]):
            return True
    return False


def unset_of(var, region, readers, macros, envl=frozenset()):
    """The value `var` holds after `region` runs with the knob unset: the last
    assignment to it outside any nested if, else the first the unset path
    may reach (a plain assignment or an atomic store), read through
    ternaries, a helper's default, a local, or a constant. UNASSIGNED when
    the unset path never assigns it."""
    v = re.escape(var)
    hits = [(m.start(), m.group(1)) for m in
            re.finditer(r"\b" + v + r"(?:\[[^\]]*\])?\s*=(?!=)\s*([^;]+);", region)]
    for m in re.finditer(r"atomic_store\w*\s*\(\s*&\s*" + v + r"\s*,", region):
        args = split_args(region[m.end():])            # the stored value, whole
        if args:
            hits.append((m.start(), args[0]))
    hits = sorted(h for h in hits if not skipped_unset(region, h[0], envl, readers))
    if not hits:
        return UNASSIGNED
    # the last assignment outside any nested if runs last on every path; with
    # none, the first one the unset path may reach
    top = [h for h in hits if not under_if(region, h[0])]
    h = top[-1] if top else hits[0]
    return eval_unset(h[1], region, envl, readers, macros)


def declared(decl):
    """The names a declaration's text (between 'static' and ';') declares."""
    out = []
    for part in split_args(decl + ")"):
        part = part.split("=")[0].split("[")[0]
        ids = re.findall(r"[A-Za-z_]\w*", part)
        if ids:
            out.append(ids[-1])
    return out


def file_statics(text):
    """Names declared at file scope as static or atomic."""
    out = set()
    text = strip_comments(text)
    for m in re.finditer(r"^(?:static|_Atomic|atomic_\w+)\b", text, re.M):
        d = decl_at(text, m.end())
        if "(" not in d.split("=")[0]:         # a variable, not a function
            out.update(declared(d))
    return out


def decl_at(text, start):
    """The declaration text from `start` to its ';', a brace initialiser
    (`= { -1, -1 }`) skipped whole."""
    i, depth = start, 0
    while i < len(text):
        ch = text[i]
        if ch in "({[":
            depth += 1
        elif ch in ")}]":
            depth -= 1
        elif ch == ";" and depth <= 0:
            return text[start:i]
        i += 1
    return text[start:]


def body_statics(body):
    """Names a body declares static, plus locals loaded from a static atomic."""
    out = set()
    inner = body[body.find("{") + 1:]
    for m in re.finditer(r"\bstatic\b", inner):
        out.update(declared(decl_at(inner, m.end())))
    return out


def assigns(var, text):
    """Whether `text` writes `var`: an assignment (plain or compound), ++/--,
    or an atomic store or exchange."""
    v = re.escape(var)
    return bool(re.search(r"\b" + v + r"(?:\[[^\]]*\])?\s*(?:[-+*/|&^]|<<|>>)?=(?!=)"
                          r"|(?:\+\+|--)\s*\b" + v + r"\b|\b" + v + r"\s*(?:\+\+|--)"
                          r"|atomic_(?:store|exchange)\w*\s*\(\s*&\s*" + v + r"\b", text))


def find_guard(body, pos, readers, macros, statics):
    """(var, op, sentinel, unset) of the latch guarding the env read at
    `pos`, or None when the read is not behind one. A guard is an `if` whose
    condition compares a variable (`v < 0`, `v == UNSET`, `!done`, either
    side of a compound) and whose statement holds the read, or an early
    `if (...) return` ahead of it, read negated. The variable must be static
    and written by the function, or it is a mode flag and the read is
    per-call; of the candidates, the outermost one its region writes is
    the latch."""
    statics = set(statics) | body_statics(body)
    for m in re.finditer(r"\b(\w+)\s*=\s*atomic_load\w*\s*\(\s*&\s*(\w+)", body):
        if m.group(2) in statics:
            statics.add(m.group(1))           # a local copy of a static atomic
    inner = body[body.find("{") + 1:]
    cands = []
    for m in re.finditer(r"\bif\s*\(", body):
        if m.start() >= pos:
            break
        c0 = m.end() - 1
        c1 = balanced(body, c0)
        cond = body[c0 + 1:c1 - 1]
        rest = body[c1:]
        st = len(rest) - len(rest.lstrip())
        if rest.lstrip().startswith("{"):
            s1 = c1 + balanced(rest, st)
        else:
            s1 = c1 + rest.find(";") + 1
        early = bool(re.match(r"\s*(?:\{\s*)?return\b[^;]*;\s*(?:\})?", rest)) and (
            not rest.lstrip().startswith("{")
            or re.fullmatch(r"\{\s*return\b[^;]*;\s*\}", rest[st:s1 - c1]) is not None)
        if not (c1 <= pos < s1) and not (early and s1 <= pos):
            continue
        cmps = [(v, op, t) for v, op, t in CMP.findall(cond)]
        cmps += [(v, "==", "0") for v in NOT.findall(cond)]
        cmps += [(v, "==", "0") for v in re.findall(r"!\s*atomic_load\w*\s*\(\s*&\s*(\w+)", cond)]
        cmps += re.findall(r"atomic_load\w*\s*\(\s*&\s*(\w+)[^()]*\)\s*(<=|>=|==|!=|<|>)\s*(\(?-?[\w.]+\)?)", cond)
        bare = re.fullmatch(r"\s*([A-Za-z_]\w*)(?:\[[^\]]*\])?\s*", cond)
        if bare:
            cmps.append((bare.group(1), "!=", "0"))      # if (x) return v;
        cmps = [c for c in cmps if c[0] in statics and assigns(c[0], inner)]
        if not cmps:
            continue
        var, op, tok = cmps[0]
        if early:
            op = NEG[op]
        region = body[c1:s1] if not early else body[s1:]
        cands.append((assigns(var, region), var, op, tok, region))
    if not cands:
        return None
    pick = next((c for c in cands if c[0]), cands[0])   # outermost the region writes
    _w, var, op, tok, region = pick
    return (var, op, num(tok, macros),
            unset_of(var, region, readers, macros, env_locals(body, readers)), tok.strip())


WAIVER = re.compile(r"env-audit-ok:[ \t]*(.*?)[ \t]*(?:\*/|\n|$)")
EMPTY_WAIVER = "(empty reason)"


def comments_only(text):
    """The text with everything but comments blanked (newlines kept), so a
    marker inside a string literal is never read."""
    out, i, n = [], 0, len(text)
    blank = lambda t: re.sub(r"[^\n]", " ", t)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(text[i:j]); i = j
        elif c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(text[i:j]); i = j
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(blank(text[i:j + 1])); i = j + 1
        else:
            out.append(c if c == "\n" else " "); i += 1
    return "".join(out)


def waiver(text, line, body):
    """The reason in an 'env-audit-ok: <reason>' comment that covers a
    function, EMPTY_WAIVER when the reason is empty, or None. A marker
    covers the function when it sits in a comment that ends on the line
    above the definition (a block comment may open further up), on the
    definition's own lines (a GNU-style 'static int' line above the name
    counts as part of it), or anywhere in the body. Only comment text is
    read, never a string literal."""
    com = comments_only(text).split("\n")
    raw = text.split("\n")
    first = line - 1                          # 0-based first line of the definition
    while first > 0 and raw[first - 1].strip() and not com[first - 1].strip() \
            and not re.search(r"[;{}#]", raw[first - 1]) and "(" not in raw[first - 1]:
        first -= 1                            # a split 'static int' line
    last = line - 1 + body.count("\n")
    start = first
    if first > 0 and com[first - 1].strip():   # the comment ending on the line above
        start = first - 1
        while start > 0 and "/*" not in com[start] and com[start - 1].strip():
            start -= 1
    m = WAIVER.search("\n".join(com[start:last + 1]))
    if not m:
        return None
    return m.group(1).strip() or EMPTY_WAIVER


RANK = {"latches": 0, "latches?": 1, "TRAP": 2}


def judge(g, body):
    """(verdict, why) for one guard; the guard prints as its source text."""
    gname, gop, gsent, unset, tok = g
    guard = f"`{gname} {gop} {tok}`"
    if unset is None:
        # the resolve branch's default array, e.g. int p[3] = { 75, .. }
        stripped = re.sub(r"static\s+[^;]*;", "", body)
        for _an, vals in ARRDEF.findall(stripped):
            unset = as_int(vals.split(",")[0])
            if unset is not None:
                break
    if unset == UNASSIGNED:
        return "TRAP", (f"the unset path never assigns {gname}, so {guard} "
                        f"holds on every call and the knob is read again each time")
    if unset is None or gsent is None:
        what = "the unset value" if unset is None else f"`{tok}`"
        return "latches?", f"guard {guard}: {what} not statically readable"
    if satisfies(unset, gop, gsent):
        return "TRAP", (f"unset resolves {gname}={unset}, which still satisfies "
                        f"{guard} -> rewrites its static every call")
    return "latches", f"unset {gname}={unset} clears {guard}"


def audit(sources):
    """sources: {relative path: text}. Returns (gate rows, {(file, function): [bodies]})."""
    defs = []
    for rel, text in sorted(sources.items()):
        for name, line, body, sig in functions(text):
            defs.append((name, line, body, sig, rel))
    readers = find_readers(defs)
    fstatics = {rel: file_statics(text) for rel, text in sources.items()}
    macros = {rel: {m.group(1): m.group(2) for m in
                    re.finditer(r"^[ \t]*#[ \t]*define[ \t]+(\w+)[ \t]+(.+?)[ \t]*$", text, re.M)}
              for rel, text in sources.items()}
    rows, allfuncs, fstatic = [], {}, set()
    for name, line, body, sig, rel in defs:
        allfuncs.setdefault((rel, name), []).append(body)   # #if/#else twins
        if re.search(r"\bstatic\b", sig):
            fstatic.add((rel, name))
        reads = env_reads(body, readers, macros.get(rel, {}))
        knobs = [k for _p, k in reads]
        if not knobs:
            continue
        verdicts = []
        for pos, _k in reads:                  # every read; the worst verdict stands
            g = find_guard(body, pos, readers, macros.get(rel, {}), fstatics[rel])
            if g is not None:
                verdicts.append(judge(g, body))
        if not verdicts:
            continue                          # per-call reads, not a latch
        v, why = max(verdicts, key=lambda x: RANK[x[0]])
        if rel.endswith(".h"):
            v, why = "TRAP", ("a lazy gate in a header is a separate static in every "
                              "file that includes it, each resolved on its own first "
                              "touch; move it into one .c file")
        rows.append(dict(file=rel, line=line, name=name, knobs=knobs,
                         verdict=v, why=why, waived=waiver(sources[rel], line, body)))

    # functions are keyed by (file, name): a call resolves to the definition
    # in its own file first (a static), else to every file's definition
    byname = {}
    for rel, name in allfuncs:
        byname.setdefault(name, []).append(rel)
    def resolve(rel, name):
        if (rel, name) in allfuncs:
            return [(rel, name)]
        return [(r, name) for r in byname.get(name, []) if (r, name) not in fstatic]
    # what each file adds to a body's references: function-like macros
    # (their bodies' calls) and file-scope tables of function names
    fmacros, tables = {}, {}
    for rel, text in sources.items():
        code = blank_strings(drop_if0(strip_comments(text)).replace("\\\n", " "))
        for m in re.finditer(r"^[ \t]*#[ \t]*define[ \t]+(\w+)\(([^)]*)\)(.*)$", code, re.M):
            fmacros.setdefault(rel, {})[m.group(1)] = m.group(3)
        for m in re.finditer(r"^[^\s#][^;{=]*=\s*\{", code, re.M):
            decl = m.group(0)[:m.group(0).rindex("=")]
            nm = re.search(r"\b(\w+)\s*\[", decl) or re.search(r"(\w+)\W*$", decl)
            init = code[m.end() - 1:balanced(code, m.end() - 1)]
            if nm:
                tables.setdefault(rel, {})[nm.group(1)] = set(re.findall(r"[A-Za-z_]\w*", init))
    def refs(rel, body):
        """Names a body calls, directly or through a same-file macro, plus
        function names it holds outside any call's arguments in a plain
        local pointer, and the functions in a file-scope table it names. A
        name stored into a member or a slot (a dispatch table being filled)
        or cast to a data pointer is not followed."""
        b = blank_strings(drop_if0(body))
        out = set(CALL.findall(b))
        for mname, mbody in fmacros.get(rel, {}).items():
            if re.search(r"\b" + mname + r"\s*\(", b):
                out |= set(CALL.findall(mbody))
        depth = 0
        for m in re.finditer(r"[()]|(?:->|\.)\s*[A-Za-z_]\w*|[A-Za-z_]\w*", b):
            t = m.group(0)
            if t == "(":
                depth += 1
            elif t == ")":
                depth -= 1
            elif t[0] in "-.":
                pass                                     # a member, not a function
            elif depth <= 0:
                before = b[max(0, m.start() - 80):m.start()]
                if re.search(r"(?:->\s*\w+|\.\s*\w+|\])\s*=\s*(?:\([^()]*\)\s*)?$", before) \
                        or re.search(r"\(\s*[\w\s]*\*\s*\)\s*$", before):
                    continue        # stored into a member or slot, or cast to data: not a call
                out.add(t)
                out |= tables.get(rel, {}).get(t, set())
        return out
    # a function handed to pthread_create or an ntp_* pool call anywhere is a
    # thread entry: never followed, even when stored in a variable or field
    # that a warm function then names
    entries = set()
    for rel, text in sources.items():
        code = blank_strings(strip_comments(text))
        for m in re.finditer(r"\b(?:pthread_create|ntp_\w+)\s*\(", code):
            for a in split_args(code[m.end():]):
                entries.update(x for x in re.findall(r"[A-Za-z_]\w*", a) if x in byname)
    def walk(frontier, keep):
        roots = set(frontier)
        seen = set()
        while frontier:
            fn = frontier.pop()
            if fn in seen or not keep(fn) or (fn[1] in entries and fn not in roots):
                continue
            seen.add(fn)
            for b in allfuncs[fn]:
                for c in refs(fn[0], b):
                    frontier += [x for x in resolve(fn[0], c) if x not in seen]
        return seen
    # the library's roots walk the library; a static elsewhere is out of reach
    warmed = walk([(r, n) for n in WARM_ROOTS for r in byname.get(n, [])],
                  lambda fn: not fn[0].startswith("cli/"))
    # the CLI resolves its own gates on the main thread before it starts the
    # GOP workers; that walk stays inside cli/, since main reaches the whole
    # library through its API table and warms none of the library's gates.
    # A thread's entry is only ever a call argument, never followed, so what
    # runs only on a worker stays cold
    warmed |= walk([(r, n) for r, n in allfuncs if n == "main"],
                   lambda fn: fn[0].startswith("cli/"))      # a main elsewhere drops out
    for r in rows:
        r["warm"] = (r["file"], r["name"]) in warmed

    return rows, allfuncs


